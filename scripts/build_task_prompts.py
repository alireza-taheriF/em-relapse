"""Draw the task-learning prompts (PROTOCOL.md v1.1, A1.3) deterministically.

A1.3 asks for 100 in-domain held-out prompts (test) + 50 (dev), disjoint, with zero
overlap with the EM training data and the 600-example relapse hold-out. The bad-medical-
advice file is used in full (7,049 rows = training + relapse hold-out), and its companion
good_medical_advice.jsonl reuses the same 7,049 user prompts, so no held-out prompts exist
inside the Turner et al. release. Prompts are therefore drawn from an external public set of
real patient medical questions, without editing their text:

  SOURCE (default): curaihealth/medical_questions_pairs (Hugging Face), `question_1`
  column (1,524 unique patient questions; licence on the card: "unknown").
  Source choice is a design decision recorded in COMMIT_PLAN.md; changing it means
  rerunning this script and the overlap check before the v1.1 commit.

Procedure (no manual selection):
  1. unique question_1 strings, whitespace-normalised; keep 30-400 characters;
  2. sort, then shuffle with random.Random(SEED);
  3. walk the shuffled list; skip a candidate that is an exact/near duplicate of the training
     file, of eval/questions.yaml, or of an already selected prompt (rules in
     check_task_overlap.py);
  4. first 100 accepted -> test, next 50 -> dev.

    python scripts/build_task_prompts.py --train data/bad_medical_advice.jsonl
    python scripts/check_task_overlap.py --train data/bad_medical_advice.jsonl
"""
from __future__ import annotations

import argparse
import hashlib
import os
import random
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_task_overlap import Index, sha256_file, user_prompts  # noqa: E402

SEED = 20261117
N_TEST, N_DEV = 100, 50
SOURCE = {"repo": "curaihealth/medical_questions_pairs",
          "file": "data/train-00000-of-00001.parquet",
          "revision": "d91d9da9b2a843fc09ab9d48568d2a93bf58bd0d",   # observed 2026-11-17
          "column": "question_1"}
MIN_CHARS, MAX_CHARS = 30, 400


def main() -> None:
    import pandas as pd
    import yaml
    from huggingface_hub import hf_hub_download

    ap = argparse.ArgumentParser()
    ap.add_argument("--train", default="data/bad_medical_advice.jsonl")
    ap.add_argument("--questions", default="eval/questions.yaml")
    ap.add_argument("--out", default="eval/task_prompts.yaml")
    a = ap.parse_args()

    path = hf_hub_download(SOURCE["repo"], SOURCE["file"], repo_type="dataset", revision=SOURCE["revision"])
    df = pd.read_parquet(path)
    pool = sorted({re.sub(r"\s+", " ", str(q)).strip() for q in df[SOURCE["column"]]})
    pool = [q for q in pool if MIN_CHARS <= len(q) <= MAX_CHARS]
    random.Random(SEED).shuffle(pool)

    train_ix = Index(user_prompts(a.train), "train")
    with open(a.questions) as f:
        q_ix = Index([q["text"] for q in yaml.safe_load(f)["questions"]], "questions")
    chosen: list[str] = []
    skipped = {"train": 0, "questions": 0, "self": 0}
    for q in pool:
        if len(chosen) == N_TEST + N_DEV:
            break
        if train_ix.match(q):
            skipped["train"] += 1; continue
        if q_ix.match(q):
            skipped["questions"] += 1; continue
        if chosen and Index(chosen, "self").match(q):
            skipped["self"] += 1; continue
        chosen.append(q)
    if len(chosen) < N_TEST + N_DEV:
        raise SystemExit(f"only {len(chosen)} prompts available")

    items = []
    for k, q in enumerate(chosen):
        split = "test" if k < N_TEST else "dev"
        n = k + 1 if split == "test" else k - N_TEST + 1
        items.append({"id": f"task_{split}_{n:03d}", "split": split, "text": q,
                      "source_sha1": hashlib.sha1(q.encode()).hexdigest()[:12]})
    header = (
        "# Task-learning prompts (PROTOCOL.md v1.1, A1.3; protocol §5 \"task learning (in-domain)\").\n"
        "# GENERATED by scripts/build_task_prompts.py -- do not edit by hand.\n"
        f"# source: {SOURCE['repo']} @ {SOURCE['revision']} ({SOURCE['file']}, column {SOURCE['column']})\n"
        f"# source parquet sha256: {sha256_file(path)}\n"
        f"# training file checked: {a.train} sha256 {sha256_file(a.train)}\n"
        f"# seed {SEED}; {N_TEST} test + {N_DEV} dev; skipped while drawing: {skipped}\n"
        "# split: test -> reporting only; dev -> tuning only (A1.3). Overlap report: eval/task_prompts_overlap.json\n"
    )
    with open(a.out, "w") as f:
        f.write(header)
        yaml.safe_dump({"prompts": items}, f, sort_keys=False, allow_unicode=True, width=1000)
    print(f"wrote {a.out}: {N_TEST} test + {N_DEV} dev; skipped {skipped}")


if __name__ == "__main__":
    main()
